const LEVEL_RANK: Record<StrategicAlignment, number> = { direct: 4, high: 3, medium: 2, weak: 1, none: 0 }

export interface MatchResult { matches: StrategyMatch[]; alignment: StrategicAlignment; score: number }

export function matchStrategy(text: string, topic: string, subtopic: string): MatchResult {
  const t = normalizeText(text)
  const declared = SUBTOPIC_TO_SECTION[subtopic]
  const matches: (StrategyMatch & { _s: number })[] = []
  for (const dir of STRATEGY_DIRECTIONS) {
    for (const sec of dir.sections) {
      const hits = sec.keywords.filter((k) => t.includes(k))
      let s = hits.length
      if (sec.name === declared) s += 2
      if (dir.name === topic) s += 1
      if (s < 1) continue
      const level: StrategicAlignment = s >= 6 ? 'direct' : s >= 4 ? 'high' : s >= 2 ? 'medium' : 'weak'
      matches.push({
        direction: dir.name, section: sec.name, level, _s: s,
        matchedKeywords: hits.slice(0, 6),
        explanation: `Найдено потенциальное соответствие разделу «${sec.name}» (направление «${dir.short}»). В тексте заявки затронуты темы: ${hits.slice(0, 4).join(', ')}. Классификация выполнена автоматически.`,
      })
    }
  }
  for (const ini of STRATEGY_INITIATIVES) {
    const kw = ini.keywords.filter((k) => t.includes(k))
    if (kw.length >= 2) {
      matches.push({
        direction: ini.direction, section: ini.section, level: 'direct', _s: 6,
        initiative: ini.name, matchedKeywords: kw.slice(0, 5),
        explanation: `Найдено потенциальное соответствие со стратегической проектной инициативой «${ini.name}» (совпадение тем: ${kw.slice(0, 3).join(', ')}). Требует экспертной проверки.`,
      })
    }
  }
  matches.sort((a, b) => LEVEL_RANK[b.level] - LEVEL_RANK[a.level] || b._s - a._s)
  const top = matches.slice(0, 3).map(({ _s, ...m }) => m)
  const alignment = top[0]?.level ?? 'none'
  return { matches: top, alignment, score: alignment === 'direct' ? 20 : alignment === 'high' ? 16 : alignment === 'medium' ? 10 : alignment === 'weak' ? 4 : 0 }
}

export function directionShort(name: string): string {
  return STRATEGY_DIRECTIONS.find((d) => d.name === name)?.short ?? name
}