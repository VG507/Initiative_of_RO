export function getPopulation(munName: string): number | null {
  if (MUNICIPALITY_POPULATION[munName]) return MUNICIPALITY_POPULATION[munName]
  const clean = munName.replace(/^город\s+/i, '').trim()
  return MUNICIPALITY_POPULATION[clean] ?? null
}
